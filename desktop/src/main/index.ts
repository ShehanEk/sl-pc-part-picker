import {
  app,
  BrowserWindow,
  Menu,
  Notification,
  Tray,
  ipcMain,
  powerMonitor,
  shell,
} from 'electron'
import { join, resolve } from 'node:path'

import { loadQueries, hasCredentials, type AdminQueries } from './monitor'
import { readPrefs, writePrefs } from './prefs'
import { RunnerHost, runnerPathFor, type JobSpec } from './runner-host'
import { Scheduler } from './scheduler'
import * as secrets from './secrets'

/**
 * PC Maker.lk desktop.
 *
 * Runs the scrape pipeline from this machine rather than from GitHub's runners,
 * which is the whole reason it exists: gamestreet.lk answers CI with 403 and
 * answers a residential connection normally, and spoofing a browser user-agent
 * was rejected as evading an access control.
 */

const DIST = __dirname
const REPO_ROOT = resolve(DIST, '..', '..')
/** Tray, window and taskbar. Generated by scripts/icons.mjs. */
const ICON = join(DIST, '..', 'assets', 'icon.ico')
const DESKTOP_DIR = resolve(DIST, '..')

/** normalize.yml's cron, 30 21 * * * UTC, in Sri Lanka time. */
const NORMALIZE_LABEL = '03:00'

/** The request-gap floor, from src/lib/http.ts. The window can raise it, never lower it. */
const MIN_DELAY_MS = 1500
const MAX_DELAY_MS = 10_000

/**
 * Whether Windows will start the app at login. `executableWillLaunchAtLogin`,
 * not `openAtLogin`: the latter only looks for an entry under Electron's own
 * default name, so with ours it always reads false. This one also turns false
 * if the user disables the entry in Task Manager, which is the truth.
 */
function startsAtLogin(): boolean {
  return app.getLoginItemSettings(loginItem()).executableWillLaunchAtLogin
}

/** Started by "Start with Windows": come up in the tray, not in the user's face. */
const START_HIDDEN = process.argv.includes('--hidden')

/**
 * What Windows runs at login. The same command as the desktop shortcut
 * (scripts/create-shortcut.ps1), so a login start also rebuilds first and never
 * runs a stale scraper; `-- --hidden` reaches electron through `npm start`.
 */
function loginItem() {
  return {
    // The registry value's name, and what Task Manager's Startup apps shows.
    // Without it Electron uses its internal app ID, which says nothing.
    name: 'PC Maker Sync',
    path: join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe'),
    args: [
      '-NoProfile',
      '-WindowStyle',
      'Hidden',
      '-Command',
      // Forward slashes: Electron drops the backslashes from the command line
      // it writes to the registry, which left a path Windows could not find.
      // PowerShell takes either.
      `Set-Location -LiteralPath '${DESKTOP_DIR.replace(/\\/g, '/')}'; npm.cmd start -- --hidden`,
    ],
  }
}

// Set before anything asks for userData. Without it Electron falls back to the
// generic "Electron" directory, which every unpackaged Electron app on the
// machine shares — not somewhere to keep a database password.
app.setName('PC Maker Sync')

let win: BrowserWindow | null = null
let tray: Tray | null = null
let runner: RunnerHost
let scheduler: Scheduler
let paused = false
let runtimeReport: { fetch: boolean; abort: boolean; getSetCookie: boolean } | null = null

type CurrentJob = {
  kind: JobSpec['kind']
  shop: string | null
  trigger: 'schedule' | 'manual'
  startedAt: string
}
/** What the "Now running" card shows; null when idle. */
let currentJob: CurrentJob | null = null

function setPaused(value: boolean) {
  paused = value
  writePrefs({ paused })
  updateTray()
}

/** Two instances would each get their own throttle map and their own queue. */
if (!app.requestSingleInstanceLock()) {
  app.quit()
}

function queries(): AdminQueries {
  return loadQueries(DIST)
}

function send(channel: string, payload: unknown) {
  win?.webContents.send(channel, payload)
}

function notify(title: string, body: string) {
  if (Notification.isSupported()) new Notification({ title, body }).show()
}

/**
 * Runs one job with its `pipeline_runs` lease.
 *
 * The lease is the only thing standing between this app and a retailer being
 * scraped twice at once by two different actors — GitHub's concurrency groups
 * cannot see a desktop run. A refusal here is a normal outcome, not an error.
 */
async function execute(spec: JobSpec, trigger: 'schedule' | 'manual'): Promise<void> {
  const q = queries()
  const label = spec.kind === 'scrape' ? spec.shop : 'normalize'

  let handle
  try {
    handle = await q.startRun({
      kind: spec.kind,
      shop: spec.kind === 'scrape' ? spec.shop : undefined,
      actor: 'desktop',
      dryRun: spec.dryRun,
    })
  } catch (err) {
    if (err instanceof q.RunInProgressError) {
      send('log', `${label}: skipped — ${err.message}`)
      return
    }
    throw err
  }

  currentJob = {
    kind: spec.kind,
    shop: spec.kind === 'scrape' ? spec.shop : null,
    trigger,
    startedAt: new Date().toISOString(),
  }
  send('job', { state: 'running', label, ...currentJob })
  updateTray()

  const outcome = await runner.run(spec)
  currentJob = null

  await q.finishRun(handle, {
    ok: outcome.ok,
    result: outcome.ok ? (outcome.result as never) : undefined,
    error: outcome.ok ? undefined : outcome.error,
    logTail: outcome.logTail,
  })

  send('job', { state: 'done', label, ok: outcome.ok })
  if (!outcome.ok) notify(`${label} failed`, outcome.error.split('\n')[0])
  updateTray()
  await pushStatus()
}

async function pushStatus() {
  if (!hasCredentials()) {
    send('status', { configured: false })
    return
  }
  try {
    const q = queries()
    const [sync, summary, runs] = await Promise.all([
      q.getShopSync(),
      q.getCatalogSummary(),
      // Enough to hold every shop's latest run for its card, not just the feed.
      q.recentRuns(60),
    ])
    send('status', {
      configured: true,
      sync,
      summary,
      runs,
      runtime: runtimeReport,
      schedule: Object.entries(q.SHOP_SCHEDULE).map(([shop, s]) => ({
        shop,
        localLabel: s.localLabel,
        ci: s.ci,
      })),
      normalizeLabel: NORMALIZE_LABEL,
      job: currentJob,
      paused,
      skipOnBattery: readPrefs().skipOnBattery,
      onBattery: powerMonitor.isOnBatteryPower(),
      nextCheckAt: scheduler?.nextCheckAt ?? null,
    })
  } catch (err) {
    send('status', {
      configured: true,
      error: err instanceof Error ? err.message : String(err),
    })
  }
}

function updateTray() {
  if (!tray) return
  const busy = runner?.busy
  tray.setToolTip(
    busy
      ? `PC Maker.lk — running ${busy.kind === 'scrape' ? busy.shop : 'normalize'}`
      : paused
        ? 'PC Maker.lk — paused'
        : 'PC Maker.lk — idle',
  )
  tray.setContextMenu(
    Menu.buildFromTemplate([
      { label: busy ? `Running ${busy.kind === 'scrape' ? busy.shop : 'normalize'}…` : 'Idle', enabled: false },
      { type: 'separator' },
      { label: 'Open dashboard', click: () => showWindow() },
      {
        label: 'Check for due syncs now',
        enabled: !busy,
        click: () => void scheduler.tick(),
      },
      {
        label: paused ? 'Resume scheduled syncs' : 'Pause scheduled syncs',
        click: () => {
          setPaused(!paused)
          void pushStatus()
        },
      },
      { label: 'Stop the running job', enabled: Boolean(busy), click: () => runner.cancel() },
      { type: 'separator' },
      { label: 'Quit', click: () => { runner.dispose(); app.exit(0) } },
    ]),
  )
}

function showWindow() {
  if (win) {
    win.show()
    win.focus()
    return
  }

  win = new BrowserWindow({
    width: 1100,
    height: 780,
    title: 'PC Maker.lk sync',
    icon: ICON,
    backgroundColor: '#f2f4f9',
    webPreferences: {
      preload: join(DIST, 'preload.cjs'),
      // Non-negotiable: log lines and table rows contain URLs scraped from
      // third-party sites. That is untrusted content rendered in this window.
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  })

  win.setMenuBarVisibility(false)
  void win.loadFile(join(DIST, '..', 'renderer', 'index.html'))

  // Nothing in this window may navigate anywhere, and nothing may open a new
  // one. External links go through the vetted opener below.
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }))
  win.webContents.on('will-navigate', (event) => event.preventDefault())

  win.on('closed', () => {
    win = null
  })
  win.once('ready-to-show', () => void pushStatus())
}

/**
 * On a first launch with nothing stored, take the repo's .env.local once.
 *
 * This is a one-time copy into encrypted storage, not an ambient load: after
 * this the app never looks at the file again, so it keeps working if the repo
 * moves and it does not quietly change behaviour when that file does. Doing it
 * on first run just saves the operator a button press they would always make.
 */
function seedCredentials() {
  if (hasCredentials()) return
  const result = secrets.importFromEnvLocal(REPO_ROOT)
  if (result.ok && result.imported.length > 0) {
    console.log(`imported ${result.imported.join(', ')} from .env.local`)
  } else if (!result.ok) {
    console.log(`no credentials yet: ${result.error}`)
  }
}

app.whenReady().then(() => {
  seedCredentials()
  paused = readPrefs().paused

  // Says which database this app is pointed at, without printing the password.
  // Also the first thing that actually decrypts the store, so a broken keychain
  // shows up here rather than as a confusing empty dashboard.
  const where = secrets.describe()
  console.log(
    where.hasDatabaseUrl
      ? `database: ${where.database ?? '?'} at ${where.host ?? '?'}`
      : 'database: not configured',
  )

  runner = new RunnerHost(runnerPathFor(DIST), {
    onLog: (line) => send('log', line),
    onRuntime: (runtime) => {
      runtimeReport = runtime
      console.log(
        `runner runtime: fetch=${runtime.fetch} abort=${runtime.abort} getSetCookie=${runtime.getSetCookie}`,
      )
      // Chromium's fetch strips Set-Cookie as a forbidden response header. The
      // Tyno scrapers read it for their session, and would fail quietly — an
      // empty price rather than an error — so this is checked, not assumed.
      if (!runtime.getSetCookie) {
        notify(
          'Runtime problem',
          'The runner has no getSetCookie. nanotek.lk and redlinetech.lk would return no prices.',
        )
      }
    },
  })

  scheduler = new Scheduler({
    runner,
    queries: queries(),
    execute,
    notify,
    isPaused: () => paused,
    skipOnBattery: () => readPrefs().skipOnBattery,
  })

  // Start the runner immediately rather than on the first job. It reports the
  // runtime it actually got, and a missing getSetCookie would otherwise stay
  // invisible until a scheduled scrape failed quietly at 3am.
  void runner.run({ kind: 'normalize', dryRun: true, limit: 0 }).catch(() => {})

  tray = new Tray(ICON)
  updateTray()
  tray.on('click', () => showWindow())

  registerIpc()
  if (!START_HIDDEN) showWindow()
  if (hasCredentials()) scheduler.start()

  // Keep the status line's "next check" and the shop ages current while the
  // window is open, without waiting for a job to finish.
  setInterval(() => {
    if (win) void pushStatus()
  }, 60_000)
})

app.on('second-instance', () => showWindow())
app.on('window-all-closed', () => {
  // Deliberately does not quit: this is a tray app, and closing the window is
  // how you get it out of the way, not how you stop it syncing.
})
app.on('before-quit', () => runner?.dispose())

function registerIpc() {
  ipcMain.handle('status', () => pushStatus())

  ipcMain.handle('settings', () => ({
    ...secrets.describe(),
    paused,
    skipOnBattery: readPrefs().skipOnBattery,
    openAtLogin: startsAtLogin(),
    minDelayMs: MIN_DELAY_MS,
    maxDelayMs: MAX_DELAY_MS,
    repoRoot: REPO_ROOT,
    runtime: runtimeReport,
  }))

  ipcMain.handle('setDelay', (_e, value: unknown) => {
    if (typeof value !== 'number' || !Number.isFinite(value)) {
      return { ok: false, error: 'Expected a number.' }
    }
    // Clamped here, not trusted from the window: the floor is not negotiable.
    const ms = Math.round(Math.min(MAX_DELAY_MS, Math.max(MIN_DELAY_MS, value)))
    const saved = secrets.set('SCRAPER_DELAY_MS', ms > MIN_DELAY_MS ? String(ms) : '')
    if (!saved.ok) return saved
    // The runner reads the gap once at start, so it restarts — after the
    // current job, never during it.
    runner.recycle()
    return { ok: true, delayMs: ms }
  })

  ipcMain.handle('setLoginItem', (_e, value: unknown) => {
    app.setLoginItemSettings({ openAtLogin: Boolean(value), ...loginItem() })
    return { ok: true, openAtLogin: startsAtLogin() }
  })

  ipcMain.handle('setSkipOnBattery', (_e, value: unknown) => {
    const prefs = writePrefs({ skipOnBattery: Boolean(value) })
    void pushStatus()
    return { ok: true, skipOnBattery: prefs.skipOnBattery }
  })

  ipcMain.handle('setSecret', (_e, key: unknown, value: unknown) => {
    if (!secrets.isSecretKey(key)) return { ok: false, error: 'Unknown setting.' }
    if (typeof value !== 'string') return { ok: false, error: 'Expected a string.' }
    return secrets.set(key, value)
  })

  ipcMain.handle('importEnv', () => secrets.importFromEnvLocal(REPO_ROOT))

  ipcMain.handle('runNow', async (_e, shop: unknown) => {
    if (typeof shop !== 'string') return { ok: false, error: 'Expected a shop.' }
    // Only shops the bundled scrapers know. A compromised renderer must not be
    // able to point this app at an arbitrary host.
    if (!queries().shopKeys.includes(shop)) return { ok: false, error: 'Unknown shop.' }
    if (runner.busy) return { ok: false, error: 'Something is already running.' }
    void execute({ kind: 'scrape', shop }, 'manual')
    return { ok: true }
  })

  ipcMain.handle('normalizeNow', async () => {
    if (runner.busy) return { ok: false, error: 'Something is already running.' }
    void execute({ kind: 'normalize' }, 'manual')
    return { ok: true }
  })

  ipcMain.handle('checkNow', async () => {
    void scheduler.tick()
    return { ok: true }
  })

  ipcMain.handle('cancel', () => {
    runner.cancel()
    updateTray()
    return { ok: true }
  })

  ipcMain.handle('setPaused', (_e, value: unknown) => {
    setPaused(Boolean(value))
    void pushStatus()
    return { ok: true, paused }
  })

  ipcMain.handle('openExternal', (_e, url: unknown) => {
    if (typeof url !== 'string') return { ok: false }
    // Shop URLs in the UI came from scraped pages. Only open ones whose origin
    // is a retailer we actually track, or the project's own repo.
    let parsed: URL
    try {
      parsed = new URL(url)
    } catch {
      return { ok: false }
    }
    const allowed =
      parsed.protocol === 'https:' &&
      (queries().TRACKED_SHOPS.some((s) => parsed.hostname.endsWith(s)) ||
        parsed.hostname === 'github.com')
    if (!allowed) return { ok: false }
    void shell.openExternal(url)
    return { ok: true }
  })
}
